"""Code -> docs links: every package and every flow file links the docs, and each link opens a section
that exists in the built pages (docs/index.html and the others, committed). docs -> code links are made
by docs/build-html.py and checked with `docs/build-html.py --check`."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parent.parent
SITE = "https://leweii.github.io/myorch/"
PAGES = {"": "docs/index.html", "workflows/": "docs/workflows/index.html"}
LINK = re.compile(re.escape(SITE) + r"((?:workflows/)?)(?:index\.html)?(?:#([^\s)\"'`>]+))?")


def ids(page: str) -> set[str]:
    return set(re.findall(r'\sid="([^"]+)"', (REPO / PAGES[page]).read_text(encoding="utf-8")))


def sources() -> list[Path]:
    files = [*REPO.glob("src/myorch/**/*.py"), *REPO.glob("flows/*.yaml"), *REPO.glob("flows/lib/*.yaml")]
    files += [p for p in REPO.rglob("README.md") if ".venv" not in p.parts and "node_modules" not in p.parts
              and p.read_text(encoding="utf-8", errors="replace").startswith("<!-- Generated by docs/")]
    return sorted(files)


def test_every_docs_link_opens_an_existing_section():
    known = {page: ids(page) for page in PAGES}
    broken = []
    for f in sources():
        for m in LINK.finditer(f.read_text(encoding="utf-8")):
            page, frag = m.group(1), m.group(2)
            if frag and frag not in known[page]:
                broken.append(f"{f.relative_to(REPO)}: {m.group(0)}")
    assert not broken, "links to sections that do not exist (rename in the code, or rebuild the docs):\n" + "\n".join(broken)


@pytest.mark.parametrize("init", sorted(REPO.glob("src/myorch/**/__init__.py")), ids=lambda p: str(p.parent.relative_to(REPO)))
def test_every_package_links_the_docs(init: Path):
    assert f"Docs: {SITE}" in init.read_text(encoding="utf-8"), f"{init.relative_to(REPO)}: add a `Docs: {SITE}#<section>` line to the docstring"


@pytest.mark.parametrize("flow", sorted([*REPO.glob("flows/*.yaml"), *REPO.glob("flows/lib/*.yaml")]), ids=lambda p: str(p.relative_to(REPO)))
def test_every_flow_file_links_the_docs(flow: Path):
    head = []
    for line in flow.read_text(encoding="utf-8").splitlines():
        if not line.startswith("#"):
            break
        head.append(line)
    assert any(line.startswith(f"# Docs: {SITE}workflows/#") for line in head), \
        f"{flow.relative_to(REPO)}: end the header comment with `# Docs: {SITE}workflows/#ch-<flow>` (or #fragments--<name>)"
