"""Build the User manual, one page with sidebar navigation: docs/index.html (the home page).

    uv run --with markdown python docs/build-html.py

Chapters are docs/README.md and docs/NN-*.md. ARCHITECTURE.md (at the repo root) is not a chapter:
links to it go to the file on GitHub.
A line `<!-- diagram: name.html -->` in a chapter is replaced by docs/diagrams/name.html, an HTML
drawing made by docs/diagrams/gen.py, so the page needs no network and no JavaScript for diagrams.

Docs and code link both ways:
- docs → code: a path in a chapter written as code (`src/myorch/core/run.py`, `core/run.py`,
  `deploy/compose.yaml`) that exists in the repo becomes a link to the file on GitHub; every chapter
  ends with a link to its own source, and the top bar links the repository.
- code → docs: every code directory a chapter mentions gets a generated README.md (GitHub shows it
  below the file list) with, for each file, the sections of the docs that describe it.
  Package docstrings and flow files carry a `Docs:` link by hand (tests/test_doc_links.py checks them).
  The Flow manual (docs/workflows/build.py) writes flows/README.md the same way.

    uv run --with markdown python docs/build-html.py --check   # exit 1 and list what is out of date
"""
from __future__ import annotations

import functools
import html
import os
import re
import subprocess
import sys
from pathlib import Path

import markdown
from markdown.extensions.toc import slugify_unicode

DOCS = Path(__file__).resolve().parent
REPO = DOCS.parent
# The pages are published from docs/ (GitHub Pages), so a link to anything else in the repo (code,
# deploy/README.md, a note's .md) points at GitHub; links between the pages and diagrams stay relative.
GITHUB = "https://github.com/leweii/myorch"
SITE = "https://leweii.github.io/myorch/"   # where docs/ is published
GENERATED_README = "<!-- Generated by docs/build-html.py from the docs' mentions of these files. Do not edit by hand. -->"


def file_link(p: Path, frag: str, page_dir: Path) -> str:
    """A link from a page in page_dir to the file p (resolved) that is not a chapter of a manual."""
    suffix = f"#{frag}" if frag else ""
    if DOCS in p.parents and p.suffix == ".html" or REPO not in [p, *p.parents]:
        return os.path.relpath(p, page_dir) + suffix
    kind = "tree" if p.is_dir() else "blob"
    return f"{GITHUB}/{kind}/main/{p.relative_to(REPO).as_posix()}{suffix}"


# ---------------------------------------------------------------- docs <-> code

CODE_BASES = [REPO, REPO / "src" / "myorch", REPO / "src"]   # `core/run.py` means src/myorch/core/run.py
ROOT_FILE = re.compile(r"^[\w.-]+\.(py|ya?ml|toml|sh|lock)$")     # bare names count only for files at the root
# A link, a code block or a heading (left as they are; a heading moves the "current section"), or inline code.
TOKEN = re.compile(r'<a\b[^>]*>.*?</a>|<pre\b.*?</pre>|<h([1-6]) id="([^"]+)">(.*?)</h\1>|<code>([^<]+)</code>', re.S)

Mentions = dict  # resolved path -> [(chapter title, section id, section title)], in page order


@functools.cache
def published() -> frozenset[Path]:
    """The files git would publish (tracked, or new and not ignored) and their directories: a path in the
    docs links only to these, so nothing points at a git-ignored file such as channels.yaml."""
    try:
        out = subprocess.run(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=REPO,
                             capture_output=True, check=True).stdout.decode()
    except (OSError, subprocess.CalledProcessError):
        return frozenset()
    files = {(REPO / f).resolve() for f in out.split("\0") if f and (REPO / f).exists()}
    return frozenset(files | {d for f in files for d in f.parents if REPO in d.parents})


def in_repo(p: Path) -> bool:
    return p in published() if published() else p.exists() and ".git" not in p.relative_to(REPO).parts


def code_path(text: str) -> Path | None:
    """The file or directory of the repo that inline code names, if it names one (no globs, no
    placeholders, nothing outside the repo)."""
    t = re.sub(r":\d+(-\d+)?$", "", html.unescape(text).strip().rstrip(".,;"))
    if not t or re.search(r"[<>*{}$\s]", t) or t.startswith(("-", "/", "~", ".", "http")):
        return None
    if "/" not in t.rstrip("/"):   # one name: a file or directory at the root only (`deploy/`, `pyproject.toml`)
        p = (REPO / t).resolve()
        return p if (t.endswith("/") or ROOT_FILE.match(t)) and in_repo(p) else None
    for base in CODE_BASES:
        p = (base / t).resolve()
        if REPO in p.parents and in_repo(p):
            return p
    return None


def code_href(p: Path) -> str:
    """Where a path written as code links to: the file on GitHub, or for a generated page under docs/
    the page on the site (the same from every page, whatever its directory)."""
    if DOCS in p.parents and p.suffix == ".html":
        return SITE + p.relative_to(DOCS).as_posix().removesuffix("index.html")
    return file_link(p, "", REPO)


def strip_tags(s: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def link_code(body: str, chapter_id: str, mentions: Mentions | None = None) -> str:
    """Inline code that names a repo file becomes a link to it on GitHub (not inside links, code
    blocks or headings). Each one is recorded in `mentions` with the section it is in."""
    title, section = "", (chapter_id, "")

    def repl(m: re.Match) -> str:
        nonlocal title, section
        if m.group(2):
            text = strip_tags(m.group(3))
            if m.group(1) == "1":
                title, section = text, (chapter_id, text)
            else:
                section = (m.group(2), text)
            return m.group(0)
        if m.group(0).startswith("<pre"):
            return link_tree(m.group(0), lambda p: mentions.setdefault(p, []).append((title, *section)) if mentions is not None else None)
        if m.group(4) is None or not (p := code_path(m.group(4))):
            return m.group(0)
        if mentions is not None:
            mentions.setdefault(p, []).append((title, *section))
        return f'<a class="code" href="{html.escape(code_href(p), quote=True)}">{m.group(0)}</a>'
    return TOKEN.sub(repl, body)


def link_tree(pre: str, mention) -> str:
    """A code block that is a directory tree rooted at a repo directory (its first line, e.g. the code
    map's `src/myorch/`; two spaces per level): each entry that exists becomes a link to it."""
    m = re.match(r"(<pre[^>]*><code[^>]*>)(.*?)(</code></pre>)", pre, re.S)
    lines = m.group(2).split("\n") if m else []
    root = code_path(lines[0].strip()) if lines else None
    if not root or not root.is_dir():
        return pre
    out, stack = [f'<a class="code" href="{html.escape(code_href(root), quote=True)}">{lines[0]}</a>'], []
    mention(root)
    for line in lines[1:]:
        # an entry: indent, then one name or a list of them ("worker.py, client.py, models.py"), then text
        lm = re.match(r"^( *)([^\s,]+(?:, [^\s,]+)*)(.*)$", line)
        if not lm:
            out.append(line)
            continue
        depth = len(lm.group(1)) // 2 - 1
        stack = stack[:max(depth, 0)]
        parts = re.split(r"(, )", lm.group(2))   # names and the separators between them
        names, seps, linked = parts[::2], parts[1::2] + [""], []
        for raw in names:
            name = html.unescape(raw)
            # entries back at the root's own indent are other top-level paths (flows/, deploy/, ...)
            p = (root.joinpath(*stack) / name).resolve() if depth >= 0 else code_path(name)
            if p and (root in p.parents or depth < 0) and in_repo(p):
                mention(p)
                raw = f'<a class="code" href="{html.escape(code_href(p), quote=True)}">{raw}</a>'
            linked.append(raw)
        if len(names) == 1 and html.unescape(names[0]).endswith("/"):
            stack.append(html.unescape(names[0]).rstrip("/"))
        out.append(lm.group(1) + "".join(n + s for n, s in zip(linked, seps)) + lm.group(3))
    return m.group(1) + "\n".join(out) + m.group(3)


def source_link(path: Path) -> str:
    """The line at the end of a chapter: its source file on GitHub."""
    rel = path.relative_to(REPO).as_posix()
    return f'<p class="src">{WORDS["source"]} <a href="{GITHUB}/blob/main/{rel}"><code>{rel}</code></a></p>'


def code_readmes(mentions: Mentions, skip: tuple[str, ...] = ("docs", "flows")) -> dict[Path, str]:
    """README.md for each code directory the docs mention something in: each mentioned entry with the
    sections of the docs that describe it. Directories with a hand-written README.md are left alone."""
    rows: dict[Path, dict[Path, list]] = {}
    for p, where in mentions.items():
        rel = p.relative_to(REPO)
        if not rel.parts or rel.parts[0] in skip:
            continue
        if p.parent != REPO:
            rows.setdefault(p.parent, {}).setdefault(p, []).extend(where)
        if p.is_dir():
            rows.setdefault(p, {}).setdefault(p, []).extend(where)
    out = {}
    for d, entries in sorted(rows.items()):
        readme = d / "README.md"
        if readme.exists() and GENERATED_README not in readme.read_text(encoding="utf-8"):
            continue
        rel = d.relative_to(REPO).as_posix()
        lines = [GENERATED_README, f"# Docs for `{rel}/`", "",
                 f"Where the [myorch docs]({SITE}) describe what is in this directory. "
                 "Each link opens the section; the paths in the docs link back here.", "",
                 "| | Described in |", "|---|---|"]
        for p, where in sorted(entries.items(), key=lambda e: (e[0] != d, not e[0].is_dir(), e[0].name)):
            name = "(this directory)" if p == d else p.name + ("/" if p.is_dir() else "")
            href = "." if p == d else p.name + ("/" if p.is_dir() else "")
            seen, links = set(), []
            for title, sid, stitle in where:
                if sid in seen:
                    continue
                seen.add(sid)
                label = title if not stitle or stitle == title else f"{title} › {stitle}"
                links.append(f"[{label}]({SITE}#{sid})")
            lines.append(f"| [`{name}`]({href}) | {' · '.join(links)} |")
        out[readme] = "\n".join(lines) + "\n"
    return out


def generated_readmes() -> list[Path]:
    """README.md files written by this script (or docs/workflows/build.py) that exist now."""
    found = []
    for p in REPO.rglob("README.md"):
        rel = p.relative_to(REPO).parts
        if rel[0] in (".git", ".venv", "node_modules", "docs") or "node_modules" in rel:
            continue
        if "<!-- Generated by docs/" in p.read_text(encoding="utf-8", errors="replace").split("\n", 1)[0]:
            found.append(p)
    return found


def write_or_check(files: dict[Path, str], check: bool, owned: list[Path] | None = None) -> list[str]:
    """Write the files (and delete the `owned` generated files no longer produced); with check, change
    nothing and return what is out of date."""
    stale = [p for p, text in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    gone = [p for p in owned or [] if p not in files]
    if not check:
        for p in stale:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(files[p], encoding="utf-8")
        for p in gone:
            p.unlink()
    return [p.relative_to(REPO).as_posix() for p in stale + gone]


FLOWS = REPO / "flows"                          # the flows' prose (flows/<flow>.md): chapters of the Flow manual
WORKFLOWS = DOCS / "workflows" / "README.md"    # the Flow manual's home
DIAGRAMS = DOCS / "diagrams"                    # the HTML drawings embedded into the chapters
WORDS = {"title": "myorch docs", "manual": "User manual", "flow_manual": "Flow manual", "home": "Home",
         "theme": "Theme", "light": "Light", "dark": "Dark", "auto": "System", "filter": "Filter chapters  /",
         "source": "Source of this page:"}


def chapters() -> list[Path]:
    return [DOCS / "README.md", *sorted(DOCS.glob("[0-9][0-9]-*.md"))]


def chapter_key(path: Path) -> str:
    return "index" if path.name == "README.md" else path.stem


def fix_links(text: str, src_dir: Path, chapter: str = "") -> str:
    """Relative links, resolved from the source file's directory: links to a chapter become in-page
    anchors, links to a flow's .md go to its chapter in the Flow manual, others are made relative
    to the directory of docs/index.html."""
    keys = {p.resolve(): chapter_key(p) for p in chapters()}

    def repl(m: re.Match) -> str:
        target = html.unescape(m.group(1))
        if target.startswith("#") and chapter and not target.startswith(("#ch-", f"#{chapter}--")):
            return f'href="#{chapter}--{html.escape(target[1:], quote=True)}"'  # a heading in the same chapter
        if re.match(r"^[a-z]+:|^#|^/", target):
            return m.group(0)
        page, _, frag = target.partition("#")
        if not page:
            return m.group(0)
        p = (src_dir / page).resolve()
        if p in keys:
            key = keys[p]
            return f'href="#{key}--{frag}"' if frag else f'href="#ch-{key}"'
        if p.parent == FLOWS and p.suffix == ".md" and p.name != "README.md":
            return f'href="workflows/index.html#{p.stem + "--" + frag if frag else "ch-" + p.stem}"'
        if p == WORKFLOWS:
            return f'href="workflows/index.html#{"index--" + frag if frag else "ch-index"}"'
        return 'href="' + html.escape(file_link(p, frag, DOCS), quote=True) + '"'
    return re.sub(r'href="([^"]+)"', repl, text)


def embed_diagrams(text: str) -> str:
    """<!-- diagram: name.html --> becomes the content of docs/diagrams/name.html (an HTML drawing)."""
    def repl(m: re.Match) -> str:
        return f'<div class="diagram">{(DIAGRAMS / m.group(1)).read_text(encoding="utf-8")}</div>'
    return re.sub(r"<!-- diagram: ([\w.-]+\.html) -->", repl, text)


def render(path: Path, mentions: Mentions) -> tuple[str, str, list]:
    key = chapter_key(path)
    md = markdown.Markdown(
        extensions=["tables", "fenced_code", "toc", "sane_lists"],
        extension_configs={"toc": {"slugify": lambda v, sep: f"{key}--{slugify_unicode(v, sep)}"}},
    )
    body = fix_links(md.convert(path.read_text(encoding="utf-8")), path.parent, key)
    body = embed_diagrams(link_code(body, f"ch-{key}", mentions)) + source_link(path)
    tokens = md.toc_tokens
    title = tokens[0]["name"] if tokens else path.name
    subs = tokens[0]["children"] if tokens else []
    return key, f'<section class="chapter" id="ch-{key}">{body}</section>', [title, subs]


def build(mentions: Mentions) -> dict[Path, str]:
    sections, nav = [], []
    labels = {"index": WORDS["home"]}
    for path in chapters():
        key, sec, (title, subs) = render(path, mentions)
        sections.append(sec)
        label = labels.get(key) or html.unescape(title)
        items = "".join(f'<li><a href="#{s["id"]}">{s["name"]}</a></li>' for s in subs) if key != "index" else ""
        nav.append(f'<li class="ch"><a class="ch-link" href="#ch-{key}">{label}</a>'
                   + (f'<ul class="sub">{items}</ul>' if items else "") + "</li>")
    xlink = f'<a class="xlink" href="workflows/index.html">{WORDS["flow_manual"]} →</a>'
    out = page(WORDS["manual"], WORDS["title"], xlink, "", "\n".join(nav), "\n".join(sections))
    return {DOCS / "index.html": out}


def main() -> None:
    check = "--check" in sys.argv
    mentions: Mentions = {}
    files = build(mentions)
    files.update(code_readmes(mentions))
    owned = [p for p in generated_readmes() if "docs/build-html.py" in p.read_text(encoding="utf-8").split("\n", 1)[0]]
    changed = write_or_check(files, check, owned)
    if check:
        if changed:
            sys.exit("out of date (run uv run --with markdown python docs/build-html.py):\n  " + "\n  ".join(changed))
        print("docs pages and code README.md files are up to date")
        return
    readmes = sum(1 for p in files if p.name == "README.md")
    print(f"wrote docs/index.html and {readmes} code README.md files ({len(changed)} changed)")


def page(sub: str, title: str, xlink: str, css: str, nav: str, body: str) -> str:
    """The page shell. docs/workflows/build.py uses it too, so both manuals look the same."""
    w = WORDS
    return (TEMPLATE.replace("{{TITLE}}", title).replace("{{SUB}}", sub).replace("{{XLINK}}", xlink)
            .replace("{{THEME}}", w["theme"]).replace("{{LIGHT}}", w["light"]).replace("{{DARK}}", w["dark"])
            .replace("{{AUTO}}", w["auto"]).replace("{{FILTER}}", w["filter"])
            .replace("{{CSS}}", css).replace("{{NAV}}", nav).replace("{{BODY}}", body))


